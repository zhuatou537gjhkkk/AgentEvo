export function getMcpFixtureCases(ids = null) {
    if (!Array.isArray(ids) || ids.length === 0) return MCP_FIXTURE_CASES.map((item) => ({ ...item }));
    const wanted = new Set(ids.map(String));
    return MCP_FIXTURE_CASES.filter((item) => wanted.has(item.id)).map((item) => ({ ...item }));
}

